import AppKit
import Combine
import CryptoKit
import ImageIO

struct ClipboardItem: Identifiable, Codable {
    var id = UUID()
    var text = ""
    var fileURLs: [URL] = []
    var imageData: Data?
    var createdAt = Date()
    var pinned = false
    var title: String {
        if let data = imageData, let source = CGImageSourceCreateWithData(data as CFData, nil),
           let props = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any] {
            return "图片 \(props[kCGImagePropertyPixelWidth] ?? 0) × \(props[kCGImagePropertyPixelHeight] ?? 0)"
        }
        if let file = fileURLs.first { return file.lastPathComponent + (fileURLs.count > 1 ? " 等 \(fileURLs.count) 个文件" : "") }
        return String(text.prefix(100))
    }
    var previewImage: NSImage? {
        guard let imageData, let source = CGImageSourceCreateWithData(imageData as CFData, nil),
              let thumbnail = CGImageSourceCreateThumbnailAtIndex(source, 0, [
                kCGImageSourceCreateThumbnailFromImageAlways: true,
                kCGImageSourceThumbnailMaxPixelSize: 128,
                kCGImageSourceCreateThumbnailWithTransform: true
              ] as CFDictionary) else { return nil }
        return NSImage(cgImage: thumbnail, size: CGSize(width: thumbnail.width, height: thumbnail.height))
    }
    var detail: String { (pinned ? "已固定 · " : "") + (imageData != nil ? "图片" : fileURLs.isEmpty ? "文本" : "文件") + " · 点击复制" }
    var symbol: String { imageData != nil ? "photo" : fileURLs.isEmpty ? "doc.text" : "doc" }
    var byteCount: Int { (imageData?.count ?? 0) + text.utf8.count + fileURLs.reduce(0) { $0 + $1.absoluteString.utf8.count } }
    var fingerprint: String {
        let data = imageData ?? Data((fileURLs.isEmpty ? "text:" + text : "files:" + fileURLs.map(\.absoluteString).joined(separator: "\n")).utf8)
        return SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }
}

@MainActor
final class ClipboardHistory: ObservableObject {
    static let shared = ClipboardHistory()
    @Published private(set) var items: [ClipboardItem] = []
    @Published var message: String?
    private let defaults: UserDefaults
    private let board: NSPasteboard
    private var changeCount: Int
    static let itemLimit = 50
    static let byteLimit = 32 * 1024 * 1024
    static let pinByteLimit = 16 * 1024 * 1024
    var orderedItems: [ClipboardItem] { items.filter(\.pinned) + items.filter { !$0.pinned } }

    init(board: NSPasteboard = .general, defaults: UserDefaults = .standard) {
        self.board = board
        self.defaults = defaults
        changeCount = board.changeCount
        if let data = defaults.data(forKey: "pinnedClipboard"), data.count <= Self.pinByteLimit * 2,
           let saved = try? JSONDecoder().decode([ClipboardItem].self, from: data) {
            for var item in saved.prefix(10) where item.byteCount <= 8 * 1024 * 1024 {
                item.pinned = true
                if items.reduce(0, { $0 + $1.byteCount }) + item.byteCount <= Self.pinByteLimit { items.append(item) }
            }
        }
    }

    func capture(now: Date = Date()) {
        prune(now: now)
        guard board.changeCount != changeCount else { return }
        changeCount = board.changeCount
        let excluded = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]
        guard !excluded.contains(where: { board.types?.contains(NSPasteboard.PasteboardType($0)) == true }) else { return }
        var item = ClipboardItem(createdAt: now)
        if let urls = board.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            item.fileURLs = Array(urls.prefix(100))
        } else if let type = [NSPasteboard.PasteboardType.png, .tiff].first(where: { board.types?.contains($0) == true }),
                  let data = board.data(forType: type), data.count <= 8 * 1024 * 1024,
                  let source = CGImageSourceCreateWithData(data as CFData, nil),
                  let props = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
                  let width = props[kCGImagePropertyPixelWidth] as? Int, let height = props[kCGImagePropertyPixelHeight] as? Int,
                  width > 0, height > 0, Double(width) * Double(height) <= 25_000_000 {
            item.imageData = data
        } else if let value = board.string(forType: .string), !value.isEmpty, value.utf8.count <= 100_000 {
            item.text = value
        } else { return }
        let fingerprint = item.fingerprint
        if let existing = items.first(where: { $0.fingerprint == fingerprint }) {
            item.id = existing.id
            item.pinned = existing.pinned
        }
        items.removeAll { $0.fingerprint == fingerprint }
        items.insert(item, at: 0)
        while items.count > Self.itemLimit || items.reduce(0, { $0 + $1.byteCount }) > Self.byteLimit {
            guard let index = items.lastIndex(where: { !$0.pinned }) else { break }
            items.remove(at: index)
        }
    }

    func prune(now: Date = Date()) {
        let minutes = defaults.object(forKey: "clipboardRetentionMinutes") as? Int ?? 60
        guard minutes > 0 else { return }
        items.removeAll { !$0.pinned && now.timeIntervalSince($0.createdAt) >= Double(minutes) * 60 }
    }

    func copy(_ item: ClipboardItem) {
        board.clearContents()
        let success: Bool
        if let data = item.imageData {
            success = board.setData(data, forType: data.starts(with: [137, 80, 78, 71]) ? .png : .tiff)
        } else if !item.fileURLs.isEmpty { success = board.writeObjects(item.fileURLs.map { $0 as NSURL }) }
        else { success = board.setString(item.text, forType: .string) }
        changeCount = board.changeCount
        message = success ? "已复制" : "复制失败，请重试"
    }

    func togglePin(_ item: ClipboardItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        if !items[index].pinned {
            guard items.filter(\.pinned).count < 10,
                  items.filter(\.pinned).reduce(0, { $0 + $1.byteCount }) + item.byteCount <= Self.pinByteLimit else {
                message = "最多固定 10 条，总大小不超过 16 MB"; return
            }
        }
        items[index].pinned.toggle()
        persistPins()
        prune()
    }
    func remove(_ item: ClipboardItem) { items.removeAll { $0.id == item.id }; persistPins() }
    func clearRecent() { items.removeAll { !$0.pinned }; message = "已清空未固定记录" }
    private func persistPins() { defaults.set(try? JSONEncoder().encode(items.filter(\.pinned)), forKey: "pinnedClipboard") }
}
